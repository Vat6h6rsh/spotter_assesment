"""Static freight trips and approximate interstate sample points; no runtime I/O.

City centres: GeoNames cities500 (CC BY 4.0), bundled in geonamescache 3.0.2.
Gorman uses an approximate municipal centre. Samples are roughly
100 miles apart, denser around junctions; these are not turn-by-turn routes.
WeatherStore forecasts the samples' H3 res-5 cell centres.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class SamplePoint:
    place: str
    lat: float
    lon: float

    @property
    def state(self) -> str:
        return self.place.rsplit(", ", 1)[1]


@dataclass(frozen=True)
class Endpoint:
    label: str
    lat: float
    lon: float
    tz: str


@dataclass(frozen=True)
class Corridor:
    road: str
    origin: Endpoint
    destination: Endpoint
    points: tuple[SamplePoint, ...]


def connected_points(corridor: Corridor, catalogue: tuple[Corridor, ...]) -> tuple[SamplePoint, ...]:
    """Join adjacent catalogue sections of the same interstate for endpoint selection."""
    points = corridor.points
    remaining = [c for c in catalogue if c != corridor and c.road == corridor.road]
    while remaining:
        for other in remaining:
            if other.points[-1] == points[0]:
                points = other.points[:-1] + points
            elif other.points[0] == points[-1]:
                points = points + other.points[1:]
            else:
                continue
            remaining.remove(other)
            break
        else:
            break
    return points


